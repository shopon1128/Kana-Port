def OrientForExport(a_point):
    """作業座標（+Yが正面）を、書き出し用の座標（-Yが正面）へ変換する。

    Blender の FBX エクスポータの既定（axis_forward='-Z', axis_up='Y'）では、
    Blender で -Y を向いているモデルが Unity で +Z（前方）を向く。
    一方このプロジェクトでは +Y を正面として作図しているので、
    書き出し前に Z軸まわり180度だけ回して辻褄を合わせる。

    これは回転（行列式 +1）であって鏡像ではないため、面の裏表もボーンの
    左右の意味も壊れない。副作用として x の符号が反転するので、
    左右非対称なパーツは pl_spec 側であらかじめ逆向きに置いてある。
    """
    return (-a_point[0], -a_point[1], a_point[2])


def SidePrefix(a_side):
    """作業座標での x の符号から、Unity Humanoid のボーン名の接頭辞を返す。

    作業座標は +Y が正面なので、キャラクターの左は **-X** 側になる
    （上を向く +Z との外積で決まる）。書き出し時の180度回転でこれが +X 側へ移り、
    Unity 上では「+X がキャラクターの左」という一般的な並びになる。

    ここを取り違えると、見た目は左右対称なので気づかないまま
    Unity で左右が入れ替わったアニメーションになる。
    """
    return "Left" if a_side < 0 else "Right"
